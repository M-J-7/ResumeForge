/**
 * Renders `measurements/enhance.json` into the block that goes in `QA.md` §11.
 *
 * ## Why the numbers are not typed into the document by hand
 *
 * §11 is a measured pass, and a measured pass whose numbers were retyped is a
 * remembered pass. This turns the artifact `pnpm qa:enhance` produced into
 * markdown, so re-running the pass and pasting the output is the whole update
 * procedure and there is no step where a figure can drift.
 *
 * What it deliberately does not do is grade anything. §11 asks a person to
 * read the proposals and say whether they would send them; this prints them
 * in full and stops.
 *
 *   pnpm qa:enhance          # produces measurements/enhance.json
 *   pnpm qa:enhance:report   # prints the markdown
 */

import { readFileSync } from "node:fs";
import path from "node:path";

const REPORT = path.join(process.cwd(), "measurements", "enhance.json");

let data;
try {
  data = JSON.parse(readFileSync(REPORT, "utf8"));
} catch {
  console.error(`No measurements at ${REPORT}. Run \`pnpm qa:enhance\` first.`);
  process.exit(1);
}

const mb = (bytes) => `${(bytes / 1_000_000).toFixed(1)} MB`;
const secs = (ms) => (ms === null || ms === undefined ? "—" : `${(ms / 1000).toFixed(1)}s`);

/**
 * How long the download takes on a connection somebody actually has.
 *
 * The measured figure comes from `localhost`, where it is a disk read and
 * describes nothing. The size is the real measurement; these are arithmetic
 * from it, and are labelled as arithmetic rather than quietly presented as
 * something that was timed.
 */
function atLinkSpeeds(bytes) {
  const bits = bytes * 8;
  return [
    ["10 Mbit/s (a poor mobile connection)", bits / 10e6],
    ["25 Mbit/s", bits / 25e6],
    ["100 Mbit/s", bits / 100e6],
  ]
    .map(([label, seconds]) => `| ${label} | ${Math.round(seconds)}s |`)
    .join("\n");
}

const out = [];
const say = (line = "") => out.push(line);

say(`<!-- Generated by \`pnpm qa:enhance:report\` from a run started ${data.startedAt}. -->`);
say();

/* ---- download ----------------------------------------------------------- */

const d = data.download;
if (d) {
  say("#### What it costs to turn on");
  say();
  say(
    `**${mb(d.totalModelBytes)} on the wire**, once per browser, across ${d.perFile.length} files.`,
  );
  say();
  say("| File | On the wire |");
  say("| ---- | ----------- |");
  for (const file of d.perFile) say(`| \`${file.file}\` | ${mb(file.bytes)} |`);
  say();
  say(
    "Smaller than the ~120 MB on disk because Next compresses what compresses: " +
      "the ONNX runtime `.wasm` goes over the wire at about a quarter of its " +
      "size, and the tokenizer at about a quarter of its own. The two `.onnx` " +
      "weight files do not shrink at all — quantized weights are already dense — " +
      "and they are the overwhelming majority of the transfer.",
  );
  say();
  say(
    "Timed from `localhost`, where it is a disk read and means nothing. The size " +
      "is the measurement; these are arithmetic from it:",
  );
  say();
  say("| Connection | Download |");
  say("| ---------- | -------- |");
  say(atLinkSpeeds(d.totalModelBytes));
  say();
  say(
    `**Peak memory ${d.peakMemoryMB} MB** ` +
      `across the whole browser process tree, **+${d.deltaMemoryMB} MB** over the same browser ` +
      "with the page open and the model not loaded. Measured at the process level " +
      "rather than with `performance.memory`, which does not see the WebAssembly " +
      "heap the weights live in, and deliberately pessimistic: it counts the " +
      "browser and GPU processes, not only the renderer holding the tab. The " +
      "target §11 names is a laptop with 8 GB.",
  );
  say();
  say(
    `**Every request during a run was same-origin.** Origins observed: ` +
      `${d.allOrigins.map((o) => `\`${o}\``).join(", ")}. ` +
      "`connect-src 'self' blob: data:` should make anything else impossible; " +
      "this is the check that the policy and the runtime configuration agree.",
  );
  say();
  if (d.webgpuAdapter) {
    say(
      `The machine had a working WebGPU adapter (\`${d.webgpuAdapter}\`) and the run ` +
        "did not touch it. See below.",
    );
    say();
  }
}

/* ---- latency ------------------------------------------------------------ */

const l = data.latency;
if (l) {
  say("#### Latency");
  say();
  say("| | |");
  say("| --- | --- |");
  const n = (l.warm ?? []).length;
  say(`| Cold (first paragraph, includes the download) | ${secs(l.coldMs)} |`);
  // The sample count is in the label rather than implied. A "median" over two
  // or three runs is a word doing more work than the data supports, and the
  // per-paragraph list below is what a reader should actually look at.
  say(`| Warm, median of ${n} | ${secs(l.warmMedianMs)} |`);
  say(`| Warm, fastest | ${secs(l.warmMinMs)} |`);
  say(`| Warm, slowest | ${secs(l.warmMaxMs)} |`);
  say();
  // Listed individually and not summarised into a claim about what drives the
  // spread. `tokenBudget()` derives `max_new_tokens` from the input length, so
  // "longer paragraph, longer run" is the obvious story — and the numbers do
  // not tell it: the shortest paragraph here was the slowest, because a model
  // that degenerates into repetition spends its whole budget. Every run:
  say("Each warm run:");
  say();
  for (const entry of l.warm ?? []) {
    say(`- ${entry.paragraph}: ${secs(entry.ms)} — ${entry.kind}`);
  }
  say();
}

/* ---- the GPU ------------------------------------------------------------ */

const g = data.gpuIrrelevance;
if (g) {
  say("#### The GPU is present and unused, and that is now correct");
  say();
  say("A browser with a working WebGPU adapter and one with none produce the same output:");
  say();
  say("```");
  say(`with a GPU : ${g.gpuAvailable}`);
  say(`GPU hidden : ${g.gpuHidden}`);
  say("```");
  say();
}

/* ---- the corpus --------------------------------------------------------- */

const c = data.corpus;
if (c) {
  say("#### Ten proposals, ten roles");
  say();
  say(
    `**${c.proposed} proposed, ${c.refused} refused — a refusal rate of ` +
      `${Math.round(c.refusalRate * 100)}%.**`,
  );
  say();
  say(
    `All ${c.withRealEvidence ?? c.total} rows are real composed prose. ` +
      "Which paragraph each row is about is in the table, and it matters: the " +
      "evidence paragraph is the one built from the user's own resume text, and " +
      "the composer can only produce it where a *bullet* names a term the skill " +
      "vocabulary knows. That is two of these ten resumes, so the rest are " +
      "measured on their opening paragraph, which is always real.",
  );
  say();
  say("| Role | Paragraph | Outcome | Time | Why |");
  say("| ---- | --------- | ------- | ---- | --- |");
  for (const row of c.rows) {
    const why = row.kind === "proposal" ? (row.summary ?? "").trim() : (row.message ?? "").trim();
    const which = (row.paragraph ?? "").replace(/ paragraph$/i, "");
    say(
      `| ${row.role} | ${which} | ${row.kind} | ${secs(row.ms)} | ${why.replace(/\|/g, "\\|")} |`,
    );
  }
  say();
  say("Every proposal in full, because the whole point of this check is reading them:");
  say();
  for (const row of c.rows) {
    if (row.kind !== "proposal") continue;
    say(`**${row.role}**`);
    say();
    say("```");
    say(`was: ${row.original}`);
    say(`now: ${row.suggested}`);
    say("```");
    say();
  }
}

/* ---- browsers ----------------------------------------------------------- */

const b = data.browsers;
if (b) {
  say("#### Browsers");
  say();
  say("| Engine | Version | Outcome | Time |");
  say("| ------ | ------- | ------- | ---- |");
  for (const [name, result] of Object.entries(b)) {
    say(`| ${name} | ${result.version} | ${result.kind} | ${secs(result.ms)} |`);
  }
  say();
  for (const [name, result] of Object.entries(b)) {
    if (result.text) say(`- **${name}**: ${result.text}`);
    else if (result.message) say(`- **${name}**: ${result.message.replace(/\[[0-9;]*m/g, "")}`);
  }
  say();

  /*
   * The WebKit row needs its explanation attached to it.
   *
   * Left as a bare "error" it reads as "the feature is broken in Safari",
   * which is not what was measured and is probably not true. What was
   * measured is that the app cannot be loaded in WebKit over plain HTTP at
   * all — an artifact of testing an https-only product on localhost.
   */
  if (b.webkit && b.webkit.kind === "error") {
    say(
      "**The WebKit row is not a result about Enhance.** The page never " +
        "finished loading, and the cause is `upgrade-insecure-requests` in our " +
        "own CSP: WebKit rewrites every subresource to `https://localhost:3000`, " +
        "where nothing is listening for TLS, and each one fails with `SSL " +
        "connect error`. Chrome and Firefox exempt localhost as a trustworthy " +
        "origin; WebKit does not.",
    );
    say();
    say(
      "That is a property of testing an https-only product over plain HTTP, not " +
        "a production defect — in production the origin *is* https and there is " +
        "nothing to upgrade. It does mean WebKit coverage of anything in this " +
        "app needs the E2E server to speak TLS, and that Safari remains " +
        "unmeasured here. Playwright's WebKit on Windows is not Safari either, " +
        "so even a passing row would have been weak evidence.",
    );
    say();
  }
}

/* ---- cancel ------------------------------------------------------------- */

const cancel = data.cancel;
if (cancel) {
  say("#### Cancel stops the work, not the spinner");
  say();
  say(
    `Over a ${cancel.windowSeconds}-second window: **${cancel.cpuSecondsWhileRunning}s** of task ` +
      `time while running, **${cancel.cpuSecondsAfterCancel}s** after Cancel. Measured with ` +
      "CDP's `TaskDuration`, so it is the tab's actual CPU rather than what the UI claims.",
  );
  say();
}

/* ---- lifecycle ---------------------------------------------------------- */

const lifecycle = data.lifecycle;
if (lifecycle) {
  say("#### Apply, reload, revert, export");
  say();
  say(
    `Applied an enhancement, saved, reloaded, reopened: the text survived. Revert ` +
      `restored the composer's original wording exactly.`,
  );
  say();
  say(
    `Exported ${Object.keys(lifecycle.exports).join(", ")} — none carried the model id or the ` +
      "`enhancement` metadata.",
  );
  say();
}

console.log(out.join("\n"));
